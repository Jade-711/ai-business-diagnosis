export function applyWorkflowPresentation(graph,positions={}){
 for(const n of graph.nodes){
  const spec=workflowNodePresentation[n.id];
  if(spec){
   n.data.nodeMeta={...n.data.nodeMeta,title:spec[0],description:spec[1]};
   if(n._temp?.externalData)n._temp.externalData={...n._temp.externalData,title:spec[0],description:spec[1]};
  }
  const p=positions[n.id];
  if(p)n.meta.position={x:p.x,y:p.y};
  if(n._temp?.bounds)Object.assign(n._temp.bounds,{x:n.meta.position.x-180,y:n.meta.position.y,...(p?.width?{width:p.width}:{}),...(p?.height?{height:p.height}:{})});
 }
 return graph;
}
